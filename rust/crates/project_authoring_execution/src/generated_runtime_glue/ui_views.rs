//! Compiler-owned named references. No source files are opened outside the leased view.
use super::*;
use engine_runtime::aui::{AuiDocument, AuiNodeKind};
use serde::Deserialize;
use std::collections::{BTreeMap, BTreeSet};

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Declaration {
    views: Vec<View>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct View {
    name: String,
    document: String,
    fields: Vec<Field>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Field {
    name: String,
    node: String,
    kind: Kind,
}

#[derive(Clone, Copy, Deserialize)]
enum Kind {
    Node,
    Text,
    Button,
    Slider,
}

impl Kind {
    fn names(self) -> (&'static str, &'static str) {
        match self {
            Self::Node => ("UiNodeRef", "node"),
            Self::Text => ("UiTextRef", "text"),
            Self::Button => ("UiButtonRef", "button"),
            Self::Slider => ("UiSliderRef", "slider"),
        }
    }

    fn accepts(self, actual: AuiNodeKind) -> bool {
        match self {
            Self::Node => true,
            Self::Text => actual == AuiNodeKind::Text,
            Self::Button => actual == AuiNodeKind::Button,
            Self::Slider => actual == AuiNodeKind::Slider,
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub(super) struct GeneratedViews {
    pub source: String,
    pub source_map: Vec<GeneratedRuntimeGlueSourceMapEntry>,
}

pub(super) fn generate(
    source: &CompilerSourceView,
    module: &CompilerRuntimeModuleSpec,
) -> Result<GeneratedViews, GeneratedRuntimeGlueError> {
    let parent = module
        .cargo_manifest
        .rsplit_once('/')
        .map_or("", |(p, _)| p);
    let path = if parent.is_empty() {
        "ui.views.json".to_string()
    } else {
        format!("{parent}/ui.views.json")
    };
    let mut output = GeneratedViews {
        source:
            "// Generated by the project compiler. Edit ui.views.json and AUI assets instead.\n"
                .into(),
        source_map: Vec::new(),
    };
    let Some(bytes) = source.bytes(&path) else {
        return Ok(output);
    };
    let declaration: Declaration =
        serde_json::from_slice(bytes).map_err(|e| invalid(&path, "", e.to_string()))?;
    let mut documents = BTreeMap::new();
    for document_path in source
        .paths()
        .filter(|p| p.starts_with("AUI/") && p.ends_with(".json"))
    {
        let value: serde_json::Value = serde_json::from_slice(source.bytes(document_path).unwrap())
            .map_err(|e| invalid(document_path, "", e.to_string()))?;
        let flat_source = value.get("nodes").is_some();
        let (_, cooked) = crate::neutral_assembler::cook_aui_document(document_path, value)
            .map_err(|e| invalid(document_path, "", e.to_string()))?;
        let document: AuiDocument = serde_json::from_value(cooked)
            .map_err(|e| invalid(document_path, "", e.to_string()))?;
        let mut nodes = BTreeSet::new();
        for node in &document.nodes {
            if !nodes.insert(&node.node_id) {
                return Err(invalid(
                    document_path,
                    "nodes",
                    format!("Duplicate node ID {}", node.node_id),
                ));
            }
        }
        if documents
            .insert(
                document.document_id.clone(),
                (document_path, document, flat_source),
            )
            .is_some()
        {
            return Err(invalid(
                document_path,
                "document_id",
                "Duplicate document ID",
            ));
        }
    }
    let mut names = BTreeSet::new();
    for (vi, view) in declaration.views.iter().enumerate() {
        let at = format!("/views/{vi}");
        if !identifier(&view.name) || !names.insert(&view.name) {
            return Err(invalid(
                &path,
                &format!("{at}/name"),
                "Invalid or duplicate Rust View name",
            ));
        }
        let (document_path, document, flat_source) =
            documents.get(&view.document).ok_or_else(|| {
                invalid(
                    &path,
                    &format!("{at}/document"),
                    format!("Unknown document {}", view.document),
                )
            })?;
        let mut field_names = BTreeSet::new();
        let mut initializers = String::new();
        output.source.push_str(&format!(
            "#[derive(Debug, Clone, Copy)]\npub struct {} {{\n",
            view.name
        ));
        for (fi, field) in view.fields.iter().enumerate() {
            let field_at = format!("{at}/fields/{fi}");
            if !identifier(&field.name) || !field_names.insert(&field.name) {
                return Err(invalid(
                    &path,
                    &format!("{field_at}/name"),
                    "Invalid or duplicate Rust field name",
                ));
            }
            let (index, node) = document
                .nodes
                .iter()
                .enumerate()
                .find(|(_, n)| n.node_id == field.node)
                .ok_or_else(|| {
                    invalid(
                        &path,
                        &format!("{field_at}/node"),
                        format!("{}: missing node {}", document_path, field.node),
                    )
                })?;
            if !field.kind.accepts(node.kind) {
                return Err(invalid(
                    &path,
                    &format!("{field_at}/kind"),
                    format!(
                        "{document_path}#/nodes/{index}: {} is {:?}, expected {}",
                        field.node,
                        node.kind,
                        field.kind.names().0
                    ),
                ));
            }
            let (ty, resolve) = field.kind.names();
            output.source.push_str(&format!(
                "    pub {}: ::project_game_sdk::aui::{ty},\n",
                field.name
            ));
            initializers.push_str(&format!(
                "            {}: ui.{resolve}({}, {})?,\n",
                field.name,
                rust_string(&view.document),
                rust_string(&field.node)
            ));
            for (origin_kind, source_path, source_symbol) in [
                ("aui_view_field", path.as_str(), field_at),
                (
                    "aui_node",
                    *document_path,
                    if *flat_source {
                        format!("/nodes/{index}")
                    } else {
                        format!("nodeId:{}", node.node_id)
                    },
                ),
            ] {
                output.source_map.push(GeneratedRuntimeGlueSourceMapEntry {
                    generated_item: format!("{}::{}", view.name, field.name),
                    origin_kind: origin_kind.into(),
                    source_path: source_path.into(),
                    source_symbol,
                });
            }
        }
        output.source.push_str(&format!("}}\nimpl {} {{\n    pub fn resolve(ui: &mut ::project_game_sdk::UiContext<'_>) -> ::core::result::Result<Self, ::project_game_sdk::aui::UiError> {{\n        ::core::result::Result::Ok(Self {{\n{initializers}        }})\n    }}\n}}\n", view.name));
    }
    Ok(output)
}

fn invalid(path: &str, field: &str, message: impl std::fmt::Display) -> GeneratedRuntimeGlueError {
    let mut error = glue_error(
        "generated_runtime_glue.ui_view_invalid",
        format!("{path}#{field}: {message}"),
        "Repair the View declaration or referenced AUI source node; never edit generated ui_views.rs.",
    );
    error.source_location = Some(Box::new(crate::game_project_compiler::SourceLocation {
        source_path: path.into(),
        field_path: Some(field.into()),
        line: None,
        column: None,
        generated: false,
    }));
    error
}

fn identifier(value: &str) -> bool {
    let mut chars = value.chars();
    matches!(chars.next(), Some(c) if c.is_ascii_alphabetic() || c == '_')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_')
        && !matches!(
            value,
            "_" | "as"
                | "async"
                | "await"
                | "break"
                | "const"
                | "continue"
                | "crate"
                | "dyn"
                | "else"
                | "enum"
                | "extern"
                | "false"
                | "fn"
                | "for"
                | "if"
                | "impl"
                | "in"
                | "let"
                | "loop"
                | "match"
                | "mod"
                | "move"
                | "mut"
                | "pub"
                | "ref"
                | "return"
                | "self"
                | "Self"
                | "static"
                | "struct"
                | "super"
                | "trait"
                | "true"
                | "type"
                | "unsafe"
                | "use"
                | "where"
                | "while"
                | "abstract"
                | "become"
                | "box"
                | "do"
                | "final"
                | "gen"
                | "macro"
                | "override"
                | "priv"
                | "try"
                | "typeof"
                | "unsized"
                | "virtual"
                | "yield"
        )
}

#[cfg(test)]
pub(super) mod tests {
    use super::*;
    use engine_runtime::aui::{AuiCanvas, AuiNode, AuiRect};

    pub(crate) fn add_views(source: &mut CompilerSourceView) {
        let mut label = AuiNode::new(
            "label",
            AuiNodeKind::Text,
            AuiRect::fixed_position(0., 0., 100., 20.),
        );
        label.parent = Some("root".into());
        let mut button = AuiNode::new(
            "button",
            AuiNodeKind::Button,
            AuiRect::fixed_position(0., 30., 100., 20.),
        );
        button.parent = Some("root".into());
        let mut slider = AuiNode::new(
            "speed",
            AuiNodeKind::Slider,
            AuiRect::fixed_position(0., 60., 100., 20.),
        )
        .with_slider(1.0, 0.5, 2.0, 0.25);
        slider.parent = Some("root".into());
        let mut root = AuiNode::new(
            "root",
            AuiNodeKind::Panel,
            AuiRect::fixed_position(0., 0., 800., 600.),
        );
        root.children = vec!["label".into(), "button".into(), "speed".into()];
        let doc = AuiDocument::new(
            "settings",
            vec![AuiCanvas::screen_overlay("main", 800., 600., "root")],
            vec![root, label, button, slider],
        );
        source.files.insert(
            "AUI/settings.json".into(),
            serde_json::to_vec(&doc).unwrap(),
        );
        source.files.insert("RuntimeModule/ui.views.json".into(), br#"{"views":[{"name":"SettingsViewRefs","document":"settings","fields":[{"name":"title","node":"label","kind":"Text"},{"name":"start","node":"button","kind":"Button"},{"name":"speed","node":"speed","kind":"Slider"}]},{"name":"Result","document":"settings","fields":[{"name":"root","node":"root","kind":"Node"}]}]}"#.to_vec());
    }

    fn fixture() -> CompilerSourceView {
        let mut source = super::super::tests::source_view("fn project_game() {}", "scene");
        add_views(&mut source);
        source
    }

    fn generate_fixture(
        source: &CompilerSourceView,
    ) -> Result<PreparedRuntimeGlue, GeneratedRuntimeGlueError> {
        generate_runtime_glue(
            source,
            Some(&super::super::tests::runtime_module()),
            TargetProfile::WindowsDev,
        )
        .map(Option::unwrap)
    }

    #[test]
    fn named_views_are_deterministic_typed_and_mapped() {
        let source = fixture();
        let a = generate_fixture(&source).unwrap();
        let b = generate_fixture(&source).unwrap();
        assert_eq!(a, b);
        assert!(a
            .ui_views
            .source
            .contains("pub title: ::project_game_sdk::aui::UiTextRef"));
        assert!(a
            .ui_views
            .source
            .contains("pub start: ::project_game_sdk::aui::UiButtonRef"));
        assert!(a
            .ui_views
            .source
            .contains("pub speed: ::project_game_sdk::aui::UiSliderRef"));
        assert!(a.ui_views.source.contains("speed: ui.slider("));
        assert!(a
            .report
            .source_map
            .iter()
            .any(|m| m.generated_item == "SettingsViewRefs::title"
                && m.source_path == "AUI/settings.json"
                && m.source_symbol == "/nodes/1"));
        let mut changed = source.clone();
        let bytes = changed
            .files
            .get_mut("RuntimeModule/ui.views.json")
            .unwrap();
        *bytes = String::from_utf8(bytes.clone())
            .unwrap()
            .replace("title", "caption")
            .into_bytes();
        assert_ne!(
            a.generation_digest(),
            generate_fixture(&changed).unwrap().generation_digest()
        );
    }

    #[test]
    fn named_views_reject_missing_renamed_or_retyped_nodes_at_source() {
        for (key, replacement) in [
            ("node_id", serde_json::json!("renamed")),
            ("kind", serde_json::json!("Button")),
        ] {
            let mut source = fixture();
            let mut doc: serde_json::Value =
                serde_json::from_slice(source.bytes("AUI/settings.json").unwrap()).unwrap();
            doc["nodes"][1][key] = replacement;
            if key == "node_id" {
                doc["nodes"][0]["children"][0] = serde_json::json!("renamed");
            }
            source.files.insert(
                "AUI/settings.json".into(),
                serde_json::to_vec(&doc).unwrap(),
            );
            let error = generate_fixture(&source).unwrap_err();
            assert!(error.message.contains("AUI/settings.json"), "{error:?}");
            let at = error.source_location.unwrap();
            assert_eq!(at.source_path, "RuntimeModule/ui.views.json");
            assert!(at.field_path.unwrap().starts_with("/views/0/fields/0/"));
        }
        let mut source = fixture();
        source.files.remove("AUI/settings.json");
        assert!(generate_fixture(&source)
            .unwrap_err()
            .message
            .contains("Unknown document"));
    }

    #[test]
    fn named_views_reject_invalid_names_and_duplicate_symbols() {
        for name in ["type", "Self", "_", "a-b", "x\";panic!()", "9view", "gen"] {
            let mut source = fixture();
            let mut declaration: serde_json::Value =
                serde_json::from_slice(source.bytes("RuntimeModule/ui.views.json").unwrap())
                    .unwrap();
            declaration["views"][0]["name"] = name.into();
            source.files.insert(
                "RuntimeModule/ui.views.json".into(),
                serde_json::to_vec(&declaration).unwrap(),
            );
            assert!(generate_fixture(&source).is_err(), "{name}");
        }
        for duplicate_view in [false, true] {
            let mut source = fixture();
            let mut declaration: serde_json::Value =
                serde_json::from_slice(source.bytes("RuntimeModule/ui.views.json").unwrap())
                    .unwrap();
            if duplicate_view {
                let copy = declaration["views"][0].clone();
                declaration["views"].as_array_mut().unwrap().push(copy);
            } else {
                declaration["views"][0]["fields"][1]["name"] = "title".into();
            }
            source.files.insert(
                "RuntimeModule/ui.views.json".into(),
                serde_json::to_vec(&declaration).unwrap(),
            );
            assert!(generate_fixture(&source)
                .unwrap_err()
                .message
                .contains("duplicate"));
        }
    }

    #[test]
    fn named_views_reject_ambiguous_assets_and_unknown_fields() {
        let mut source = fixture();
        source.files.insert(
            "AUI/duplicate.json".into(),
            source.bytes("AUI/settings.json").unwrap().to_vec(),
        );
        assert!(generate_fixture(&source)
            .unwrap_err()
            .message
            .contains("Duplicate document"));
        let mut source = fixture();
        let mut doc: serde_json::Value =
            serde_json::from_slice(source.bytes("AUI/settings.json").unwrap()).unwrap();
        doc["nodes"][2]["node_id"] = "label".into();
        source.files.insert(
            "AUI/settings.json".into(),
            serde_json::to_vec(&doc).unwrap(),
        );
        assert!(generate_fixture(&source)
            .unwrap_err()
            .message
            .to_lowercase()
            .contains("duplicate"));
        let mut source = fixture();
        source.files.insert(
            "RuntimeModule/ui.views.json".into(),
            br#"{"views":[],"typo":true}"#.to_vec(),
        );
        assert!(generate_fixture(&source)
            .unwrap_err()
            .message
            .contains("unknown field"));
    }

    #[test]
    fn named_views_consume_the_same_legacy_conversion_as_packages() {
        let mut source = fixture();
        let mut declaration: serde_json::Value =
            serde_json::from_slice(source.bytes("RuntimeModule/ui.views.json").unwrap()).unwrap();
        declaration["views"][0]["fields"]
            .as_array_mut()
            .unwrap()
            .retain(|field| field["node"] != "speed");
        source.files.insert(
            "RuntimeModule/ui.views.json".into(),
            serde_json::to_vec(&declaration).unwrap(),
        );
        source.files.insert("AUI/settings.json".into(), br#"{"documentId":"settings","root":{"nodeId":"root","nodeType":"panel","children":[{"nodeId":"label","nodeType":"text"},{"nodeId":"button","nodeType":"button"}]}}"#.to_vec());
        let output = generate_fixture(&source).unwrap();
        assert!(output
            .report
            .source_map
            .iter()
            .any(|m| m.origin_kind == "aui_node" && m.source_symbol == "nodeId:label"));
        assert!(output
            .ui_views
            .source
            .contains("::core::result::Result<Self"));
    }

    #[test]
    fn named_views_materialization_removes_stale_generated_fields() {
        let root = super::super::tests::temp_root("ui-views-materialize");
        let _cleanup = super::super::tests::TestDirectoryGuard(root.clone());
        let mut source = fixture();
        let a = generate_fixture(&source).unwrap();
        a.materialize(&root, Path::new("sdk"), Path::new("../RuntimeModule"))
            .unwrap();
        assert!(fs::read_to_string(root.join("ui_views.rs"))
            .unwrap()
            .contains("SettingsViewRefs"));
        source.files.remove("RuntimeModule/ui.views.json");
        let b = generate_fixture(&source).unwrap();
        b.materialize(&root, Path::new("sdk"), Path::new("../RuntimeModule"))
            .unwrap();
        assert!(!fs::read_to_string(root.join("ui_views.rs"))
            .unwrap()
            .contains("SettingsViewRefs"));
        assert_ne!(a.generation_digest(), b.generation_digest());
    }
}
