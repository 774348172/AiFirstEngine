//! BM-14 static scope inspection at the existing Compiler output boundary.
use super::{BenchmarkError, BenchmarkResult, FoundationCellPayload, StaticCookEvidence};
use crate::PreparedRuntimePackage;
use engine_runtime::{
    canonical_digest::sha256_prefixed,
    render_contract::{CookedRenderAsset, RenderAssetData, RenderContract},
    runtime_package_builder::RuntimePackageBuildInput,
    spatial_contract::RuntimeSpatial,
};
use serde::Serialize;
use std::collections::{BTreeMap, BTreeSet};

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct FoundationStaticCookEvidence {
    pub static_scene: StaticCookEvidence,
    pub cells: Vec<FoundationCellPayload>,
}

pub fn inspect_foundation_static_cook(
    prepared: &PreparedRuntimePackage,
) -> BenchmarkResult<FoundationStaticCookEvidence> {
    Ok(FoundationStaticCookEvidence {
        static_scene: inspect_input(
            prepared.runtime_package_build_input(),
            (10000, 10000, 256, 64),
        )?,
        cells: super::inspect_foundation_cells(prepared)?,
    })
}

fn static_id(id: &str, kind: &str) -> bool {
    id.strip_prefix(kind)
        .and_then(|tail| tail.strip_prefix('-'))
        .is_some_and(|tail| !tail.is_empty() && tail.bytes().all(|b| b.is_ascii_digit()))
}

fn inspect_input(
    input: &RuntimePackageBuildInput,
    counts: (usize, usize, usize, usize),
) -> BenchmarkResult<StaticCookEvidence> {
    let invalid = |message| BenchmarkError::new("benchmark.static_payload_ineligible", message);
    let mut meshes = BTreeMap::new();
    let mut materials = BTreeMap::new();
    let mut geometry = BTreeSet::new();
    let mut digests = BTreeMap::new();
    let mut vertex_bytes = 0;
    let mut index_bytes = 0;
    // Static IDs are generated by the existing grid recipe; foundation cell IDs
    // are disjoint and validated separately, so they cannot inflate static counts.
    for asset in &input.assets {
        if !(static_id(&asset.asset_id, "mesh") || static_id(&asset.asset_id, "material")) {
            continue;
        }
        let bytes = asset
            .runtime_payload
            .as_ref()
            .ok_or_else(|| invalid(asset.asset_id.clone()))?;
        let cooked = RenderContract::<CookedRenderAsset>::decode(
            std::str::from_utf8(bytes).map_err(|e| invalid(e.to_string()))?,
        )
        .map_err(|e| invalid(e.to_string()))?
        .data;
        digests.insert(asset.asset_id.clone(), sha256_prefixed(bytes));
        match cooked.asset {
            RenderAssetData::Mesh(mesh) => {
                if mesh.vertex_count != 600 || mesh.index_count != 3000 {
                    return Err(invalid(format!("wrong topology: {}", asset.asset_id)));
                }
                if !geometry.insert(sha256_prefixed(&mesh.vertex_bytes)) {
                    return Err(invalid(format!("duplicate geometry: {}", asset.asset_id)));
                }
                vertex_bytes += mesh.vertex_bytes.len() as u64;
                index_bytes += mesh.index_bytes.len() as u64;
                meshes.insert(asset.asset_id.as_str(), 1000u64);
            }
            RenderAssetData::Material(material) => {
                let texture = material
                    .textures
                    .get("baseColorTexture")
                    .ok_or_else(|| invalid(format!("no baseColor: {}", asset.asset_id)))?;
                materials.insert(asset.asset_id.as_str(), texture.reference.id.clone());
            }
        }
    }
    let mut textures = BTreeSet::new();
    let mut pixel_digests = BTreeSet::new();
    let mut texture_bytes = 0;
    for texture in &input.texture_payloads {
        if !static_id(&texture.metadata.asset_id, "texture") {
            continue;
        }
        if texture.metadata.width != 2048
            || texture.metadata.height != 2048
            || texture.rgba8.len() != 2048 * 2048 * 4
            || texture
                .rgba8
                .chunks_exact(4)
                .all(|p| p == &texture.rgba8[..4])
            || !pixel_digests.insert(sha256_prefixed(&texture.rgba8))
        {
            return Err(invalid(format!(
                "wrong, constant or shared pixels: {}",
                texture.metadata.asset_id
            )));
        }
        texture_bytes += texture.rgba8.len() as u64;
        textures.insert(texture.metadata.asset_id.as_str());
    }
    let mut bound_meshes = BTreeSet::new();
    let mut bound_materials = BTreeSet::new();
    let mut bound_textures = BTreeSet::new();
    let mut instances = 0;
    for scene in &input.scenes {
        let parents: BTreeMap<_, _> = scene
            .entities
            .iter()
            .map(|e| (e.id.as_str(), e.parent_id.as_deref()))
            .collect();
        let hidden: BTreeSet<_> = scene
            .entities
            .iter()
            .filter(|e| {
                !e.enabled
                    || matches!(&e.spatial,
            Some(RuntimeSpatial::World3D { visibility:Some(v), .. }) if !v.visible)
            })
            .map(|e| e.id.as_str())
            .collect();
        for entity in &scene.entities {
            let Some(RuntimeSpatial::World3D {
                mesh_renderer: Some(renderer),
                ..
            }) = &entity.spatial
            else {
                continue;
            };
            if !static_id(&renderer.mesh.0.id, "mesh") {
                continue;
            }
            let mut ancestor = Some(entity.id.as_str());
            let mut visible = renderer.visible;
            while let Some(id) = ancestor {
                if hidden.contains(id) {
                    visible = false;
                    break;
                }
                ancestor = parents.get(id).copied().flatten();
            }
            if !visible {
                continue;
            }
            let mesh_id = renderer.mesh.0.id.as_str();
            if !meshes.contains_key(mesh_id) {
                return Err(invalid(format!("unresolved mesh {mesh_id}")));
            }
            bound_meshes.insert(mesh_id);
            instances += 1;
            for reference in renderer.materials.values() {
                let id = reference.0.id.as_str();
                let texture = materials
                    .get(id)
                    .ok_or_else(|| invalid(format!("unresolved material {id}")))?;
                if !textures.contains(texture.as_str()) {
                    return Err(invalid(format!("unresolved texture {texture}")));
                }
                bound_materials.insert(id);
                bound_textures.insert(texture.as_str());
            }
        }
    }
    if (instances, meshes.len(), materials.len(), textures.len()) != counts
        || bound_meshes.len() != counts.1
        || bound_materials.len() != counts.2
        || bound_textures.len() != counts.3
    {
        return Err(invalid(format!(
            "expected {counts:?}; actual enabled/bound {instances}/{}/{}/{}; cooked {}/{}/{}",
            bound_meshes.len(),
            bound_materials.len(),
            bound_textures.len(),
            meshes.len(),
            materials.len(),
            textures.len()
        )));
    }
    Ok(StaticCookEvidence {
        render_instances: instances,
        unique_meshes: meshes.len(),
        unique_materials: materials.len(),
        unique_textures: textures.len(),
        unique_geometry_triangles: meshes.len() as u64 * 1000,
        source_instance_triangle_sum: instances as u64 * 1000,
        vertex_bytes,
        index_bytes,
        base_color_decoded_bytes: texture_bytes,
        payload_digests: digests,
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn static_inspector_rejects_hidden_unbound_shared_and_wrong_payloads() {
        let root = std::path::PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .join("../../../samples/platform_3d_benchmark_project");
        let mut session = crate::ProjectAuthoringSession::open(root).unwrap();
        let paths = session
            .source_inventory()
            .unwrap()
            .entries
            .into_iter()
            .map(|e| e.relative_path)
            .collect();
        let lease = session
            .acquire_snapshot_lease("static-inspector", paths)
            .unwrap();
        let prepared = crate::GameProjectCompiler::bind(&lease)
            .unwrap()
            .prepare(&lease, crate::TargetProfile::WindowsDev)
            .unwrap();
        let baseline = prepared.runtime_package_build_input();
        inspect_input(baseline, (10000, 100, 32, 8)).unwrap();
        let mut with_cells = baseline.clone();
        let mut material = with_cells
            .assets
            .iter()
            .find(|a| a.asset_id == "material-000")
            .unwrap()
            .clone();
        material.asset_id = "material-a-0".into();
        with_cells.assets.push(material);
        inspect_input(&with_cells, (10000, 100, 32, 8)).unwrap();
        for variant in [
            "hidden",
            "unbound",
            "shared-texture",
            "extent",
            "shared-geometry",
        ] {
            let mut input = baseline.clone();
            match variant {
                "hidden" => input.scenes[0].entities[0].enabled = false,
                "unbound" => {
                    if let Some(RuntimeSpatial::World3D {
                        mesh_renderer: Some(r),
                        ..
                    }) = &mut input.scenes[0].entities[0].spatial
                    {
                        r.materials.clear();
                        // Remove the only binding of material-000 from every instance.
                        for e in &mut input.scenes[0].entities {
                            if let Some(RuntimeSpatial::World3D {
                                mesh_renderer: Some(r),
                                ..
                            }) = &mut e.spatial
                            {
                                r.materials.retain(|_, v| v.0.id != "material-000");
                            }
                        }
                    }
                }
                "shared-texture" => {
                    input.texture_payloads[1].rgba8 = input.texture_payloads[0].rgba8.clone()
                }
                "extent" => input.texture_payloads[0].metadata.width = 1024,
                "shared-geometry" => {
                    let indices: Vec<_> = input
                        .assets
                        .iter()
                        .enumerate()
                        .filter(|(_, a)| a.asset_type == "mesh")
                        .map(|(i, _)| i)
                        .collect();
                    let first: serde_json::Value = serde_json::from_slice(
                        input.assets[indices[0]].runtime_payload.as_ref().unwrap(),
                    )
                    .unwrap();
                    let mut second: serde_json::Value = serde_json::from_slice(
                        input.assets[indices[1]].runtime_payload.as_ref().unwrap(),
                    )
                    .unwrap();
                    second["data"]["asset"]["payload"]["vertexBytes"] =
                        first["data"]["asset"]["payload"]["vertexBytes"].clone();
                    input.assets[indices[1]].runtime_payload =
                        Some(serde_json::to_vec(&second).unwrap());
                }
                _ => unreachable!(),
            }
            assert!(
                inspect_input(&input, (10000, 100, 32, 8)).is_err(),
                "{variant}"
            );
        }
    }
}
